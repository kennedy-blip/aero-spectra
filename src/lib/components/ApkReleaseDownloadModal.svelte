<script>
  import { onMount } from 'svelte';
  import { strToU8, zipSync } from 'fflate';
  import QRCode from 'qrcode';
  export let open = false;
  export let onClose = () => {};
  let qrSvg = '';
  let releaseUrl = '';
  let releaseSource = 'checking';
  let fingerprint = 'Checking release checksum…';
  let releaseState = 'Checking release artifact…';
  let busy = false;
  const version = '1.21.0';
  const githubRepo = 'kennedy-blip/aero-spectra';
  const assetName = `aero-spectra-v${version}-universal.apk`;
  const releasePath = `/releases/${assetName}`;
  async function refreshQr() {
    try { qrSvg = await QRCode.toString(releaseUrl, { type: 'svg', margin: 1, width: 140, color: { dark: '#0b1721', light: '#ffffff' } }); } catch { qrSvg = ''; }
  }
  onMount(async () => {
    releaseUrl = `${window.location.origin}${releasePath}`;
    try {
      const localArtifact = await fetch(releasePath, { method: 'HEAD' });
      if (localArtifact.ok) {
        releaseSource = 'local';
        releaseState = 'Web release artifact available';
        fingerprint = 'Calculated from APK on download';
      } else {
        const response = await fetch(`https://api.github.com/repos/${githubRepo}/releases/tags/v${version}`, { headers: { Accept: 'application/vnd.github+json' } });
        if (response.ok) {
          const release = await response.json();
          const apk = release.assets?.find((asset) => asset.name === assetName);
          if (apk?.browser_download_url) {
            releaseSource = 'github';
            releaseUrl = apk.browser_download_url;
            releaseState = 'GitHub release APK available';
            fingerprint = 'SHA-256 checksum attached to release';
          } else {
            releaseSource = 'fallback';
            releaseState = 'Preview bundle fallback';
            fingerprint = 'No matching APK in this release';
          }
        } else {
          releaseSource = 'fallback';
          releaseState = 'Preview bundle fallback';
          fingerprint = 'Generated by Android CI after a version tag';
        }
      }
    } catch {
      releaseSource = 'fallback';
      releaseState = 'Preview bundle fallback';
      fingerprint = 'Generated by Android CI after a version tag';
    }
    await refreshQr();
  });
  function downloadBlob(blob, name) {
    const url = URL.createObjectURL(blob); const link = document.createElement('a'); link.href = url; link.download = name; link.click();
    setTimeout(() => URL.revokeObjectURL(url), 1500);
  }
  async function downloadRelease() {
    busy = true;
    try {
      if (releaseSource === 'github') {
        const link = document.createElement('a');
        link.href = releaseUrl;
        link.target = '_blank';
        link.rel = 'noopener noreferrer';
        link.click();
        releaseState = 'Opening GitHub release APK';
        return;
      }
      let response;
      try { response = await fetch(releasePath); } catch { response = { ok: false }; }
      if (response.ok) {
        const blob = await response.blob();
        const hash = await crypto.subtle.digest('SHA-256', await blob.arrayBuffer());
        fingerprint = [...new Uint8Array(hash)].map((b) => b.toString(16).padStart(2, '0')).join('').toUpperCase();
        releaseState = 'Release APK downloaded';
        downloadBlob(blob, `aero-spectra-v${version}-universal.apk`);
      } else {
        const readme = `AERO-SPECTRA Android preview bundle v${version}\n\nThis is a ZIP-based preview package, not an installable Android APK. A version-tagged Android CI build publishes the genuine APK and SHA-256 file to https://github.com/kennedy-blip/aero-spectra/releases.\n\nPackage: com.aerospectra.hygiene\nCapacitor: 6\nMin SDK: 26 · Target SDK: 34\n`;
        const archive = zipSync({
          'README-PREVIEW.txt': strToU8(readme),
          'AndroidManifest.xml': strToU8('<manifest xmlns:android="http://schemas.android.com/apk/res/android" package="com.aerospectra.hygiene"><uses-sdk android:minSdkVersion="26" android:targetSdkVersion="34"/><application android:label="Aero-Spectra"/></manifest>'),
          'assets/runtime-metadata.json': strToU8(JSON.stringify({ name: 'AERO-SPECTRA', version, packageId: 'com.aerospectra.hygiene', capacitor: 6, nativePlugins: ['MacroTyndallCameraTorchPlugin', 'AeroAcousticAmbientSensorPlugin'], note: 'Preview metadata archive; not an installable APK.' }, null, 2)),
          'assets/index.html': strToU8('<!doctype html><meta charset="utf-8"><title>Aero-Spectra offline package</title><p>Installable binary is attached by the Android CI workflow.</p>')
        }, { level: 6 });
        const blob = new Blob([archive], { type: 'application/zip' });
        downloadBlob(blob, `aero-spectra-v${version}-preview-bundle.zip`);
        releaseState = 'Downloaded preview ZIP · not installable';
      }
    } finally { busy = false; }
  }
</script>

{#if open}
  <div class="modal-backdrop" role="presentation" on:click={(event) => event.target === event.currentTarget && onClose()}>
    <dialog open class="apk-modal glass-modal" aria-modal="true" aria-labelledby="apk-title">
      <header class="modal-head"><div><span class="eyebrow">NATIVE ANDROID · RELEASE CHANNEL</span><h2 id="apk-title">Aero-Spectra APK</h2></div><button class="close-button" on:click={onClose} aria-label="Close APK dialog">×</button></header>
      <div class="apk-hero"><div class="qr-wrap">{#if qrSvg}<div class="qr-svg">{@html qrSvg}</div>{:else}<div class="qr-loading">QR</div>{/if}</div><div class="apk-release"><span class="release-tag"><i></i>{releaseState}</span><strong>Version {version}</strong><p>Android environmental workstation · universal release channel</p><button class="download-button" on:click={downloadRelease} disabled={busy || releaseSource === 'checking'}>{busy ? 'Preparing…' : releaseSource === 'fallback' ? '↓  Download preview ZIP · not installable' : '↓  Download Android package'}</button></div></div>
      <div class="apk-telemetry"><div><small>APPLICATION ID</small><b>com.aerospectra.hygiene</b></div><div><small>CAPACITOR</small><b>6 · Min 26 / Target 34</b></div><div><small>NATIVE MODULES</small><b>Camera2 · AudioRecord</b></div><div class="fingerprint"><small>SHA-256 INTEGRITY</small><b>{fingerprint}</b></div></div>
      <p class="apk-note"><strong>Preview safety note:</strong> if no CI artifact is available, the fallback is a clearly labeled ZIP preview—not an APK and not installable. A version-tagged GitHub Actions build publishes the real package and SHA-256 checksum. Verify provenance and signing before installation.</p>
      <footer class="modal-foot"><span>SCAN TO OPEN RELEASE URL</span><button class="text-button" on:click={onClose}>Close</button></footer>
    </dialog>
  </div>
{/if}

